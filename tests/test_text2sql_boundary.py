def test_read_only_regression_cases_live_on_canonical_path() -> None:
    from gustobot.application.agents.text2sql.components.sql_execution.node import (
        _is_read_only_query,
    )

    cases = [
        ("SELECT * FROM recipes", True),
        ("SELECT cuisine, COUNT(*) FROM recipes GROUP BY cuisine", True),
        ("-- generated by llm\nSELECT * FROM recipes", True),
        ("/* generated */\nSELECT * FROM recipes", True),
        ("DELETE FROM recipes", False),
        ("UPDATE recipes SET name='x'", False),
        ("INSERT INTO recipes(id) VALUES (1)", False),
        ("DROP TABLE recipes", False),
        ("SELECT * FROM recipes; DELETE FROM recipes", False),
        ("WITH cte AS (SELECT * FROM recipes) SELECT * FROM cte", True),
        (
            "WITH cte AS (SELECT id FROM recipes) "
            "DELETE FROM recipes WHERE id IN (SELECT id FROM cte)",
            False,
        ),
        (
            "WITH cte AS (SELECT id FROM recipes) "
            "UPDATE recipes SET name='x' WHERE id IN (SELECT id FROM cte)",
            False,
        ),
        (
            "WITH cte AS (SELECT id FROM recipes) "
            "INSERT INTO recipes(id) SELECT id FROM cte",
            False,
        ),
        ("SELECT * FROM recipes INTO OUTFILE '/tmp/recipes.txt'", False),
        ("SELECT * FROM recipes INTO DUMPFILE '/tmp/recipes.bin'", False),
        ("SELECT 'INTO OUTFILE' AS text", True),
        ("SELECT 'INTO DUMPFILE' AS text", True),
    ]

    for sql, expected in cases:
        assert _is_read_only_query(sql) is expected, sql


def test_sql_agent_error_contract_is_explicitly_sql(monkeypatch) -> None:
    from gustobot.application.agents.tool_execution.sql_agent import (
        SQLAgent,
        create_sql_agent_node,
    )
    from gustobot.config import settings

    monkeypatch.setattr(settings, "LLM_API_KEY", "")

    node = create_sql_agent_node()
    output = asyncio.run(node({"task": "统计 recipes 表中的记录数"}))
    node_result = output["tool_results"][0]

    agent_result = asyncio.run(SQLAgent().execute("统计 recipes 表中的记录数"))

    for tool_result in (node_result, agent_result):
        assert tool_result.tool_name == "text2sql_query"
        assert tool_result.tool_kind == "sql"
        assert tool_result.status == "error"
        assert tool_result.task == "统计 recipes 表中的记录数"


