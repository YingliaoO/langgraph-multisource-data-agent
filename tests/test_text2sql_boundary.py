def test_sql_agent_promotes_read_only_validation_code_to_tool_metadata(monkeypatch) -> None:
    import gustobot.application.agents.text2sql as text2sql_package
    import gustobot.application.agents.tool_execution.sql_agent as sql_agent_module
    from gustobot.config import settings

    class FakeWorkflow:
        async def ainvoke(self, _state):
            return {
                "answer": "抱歉，生成的 SQL 未通过安全校验。",
                "sql_statement": "DELETE FROM recipes",
                "execution_results": None,
                "execution_error": None,
                "steps": ["sql_validation"],
                "validation_errors": ["只允许只读查询"],
                "validation_error_codes": ["READ_ONLY_POLICY_VIOLATION"],
                "validation_warnings": [],
                "validation_retryable": False,
                "referenced_tables": ["recipes"],
                "referenced_columns": {},
                "repair_count": 0,
                "max_repairs": 1,
            }

    monkeypatch.setattr(settings, "LLM_API_KEY", "test-key")
    monkeypatch.setattr(sql_agent_module, "_get_text2sql_llm", lambda: object())
    monkeypatch.setattr(
        text2sql_package,
        "create_text2sql_workflow",
        lambda **_kwargs: FakeWorkflow(),
    )

    output = asyncio.run(
        sql_agent_module.create_sql_agent_node()(
            {"task": "请通过 SQL 删除 recipes 表中的所有数据。"}
        )
    )
    result = output["tool_results"][0]

    assert result.status == "error"
    assert result.metadata["error_code"] == "READ_ONLY_POLICY_VIOLATION"
    assert result.metadata["error"] == "只允许只读查询"


def test_sql_agent_propagates_connection_and_uses_configured_max_rows(monkeypatch) -> None:
    import gustobot.application.agents.text2sql as text2sql_package
    import gustobot.application.agents.tool_execution.sql_agent as sql_agent_module
    from gustobot.config import settings

    captured = {}

    class FakeWorkflow:
        async def ainvoke(self, state):
            captured["state"] = state
            return {
                "answer": "无结果",
                "sql_statement": "SELECT 1",
                "execution_results": [],
                "execution_error": None,
                "steps": ["sql_execution"],
                "validation_errors": [],
                "validation_error_codes": [],
                "validation_warnings": [],
                "referenced_tables": [],
                "referenced_columns": {},
                "repair_count": 0,
                "max_repairs": 1,
            }

    def fake_create_workflow(**kwargs):
        captured["workflow"] = kwargs
        return FakeWorkflow()

    database_url = "mysql+pymysql://user:pass@db-b:3306/retail"
    monkeypatch.setattr(settings, "LLM_API_KEY", "test-key")
    monkeypatch.setattr(settings, "SQL_AGENT_MAX_ROWS", 37)
    monkeypatch.setattr(sql_agent_module, "_get_text2sql_llm", lambda: object())
    monkeypatch.setattr(text2sql_package, "create_text2sql_workflow", fake_create_workflow)

    asyncio.run(
        sql_agent_module.create_sql_agent_node()(
            {
                "task": "查询订单",
                "query_parameters": {"connection_string": database_url},
            }
        )
    )

    assert captured["workflow"]["connection_string"] == database_url
    assert captured["state"]["connection_string"] == database_url
    assert captured["state"]["max_rows"] == 37
